/**
 * The verbs `ThinkingIndicator` rotates through while an agent thinks (#7870). Maintainer,
 * 2026-11-27: "lets do like anthropic, let it combobulate and have like 200-300 verbs".
 *
 * THE VOICE. Sentence case, ending in "…", no emoji, no exclamation marks. Playful, but about the
 * things Alethia is about: focus, truth, instruments, measurement, craft.
 *
 * THE ONE HARD RULE. A verb never claims an action the agent is not taking. This rotates while a
 * model is THINKING, inside a product that really does deploy, apply and destroy infrastructure, so
 * "Deploying…" beside a plan that has not been approved is a lie a user would act on. Every verb
 * here is something that happens in a head, at a bench or in a notebook — never to a cluster, a
 * repository, a file or a bill. `BANNED_VERB_STEMS` is the mechanical half of that rule and the
 * test reads every entry against it; it is a floor, not the whole rule, so a new verb is also read
 * by a person for what it would make a user believe.
 */

