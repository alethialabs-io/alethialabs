/**
 * What `src/brand.generated.ts` must contain, computed from packages/brand itself.
 *
 * The Worker has no React at runtime, so it cannot draw `AlethiaLockup`. Instead this module renders
 * the real component with react-dom/server, lifts the lockup's CSS out of the real tokens.css, and
 * takes the favicon from the same constants the sites' `icon.tsx` draws. `scripts/gen-brand.ts`
 * writes the result into the module the Worker imports; `tests/brand.test.ts` recomputes it and fails
 * when the committed module no longer matches. Neither side holds a copy of the value.
 */

import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

import { faviconSvg } from "@repo/brand/icon-svg";
import { AlethiaLockup } from "@repo/brand/lockup";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

/** The status header's lockup: the main site header's `tag="labs"`, sized by `.ah-mark`'s responsive default. */
export function lockupHtml(): string {
	return renderToStaticMarkup(createElement(AlethiaLockup, { tag: "labs" }));
}

/** The opening line of the lockup's section in tokens.css; the section runs to the next banner or EOF. */
const LOCKUP_SECTION = "The lockup — AlethiaLockup";
const BANNER = "/* ============================================================";

/** Reads packages/brand/src/tokens.css through the package's own export, wherever the workspace sits. */
function tokensCss(): string {
	const req = createRequire(join(process.cwd(), "package.json"));
	return readFileSync(req.resolve("@repo/brand/tokens.css"), "utf8");
}

/**
 * The `.ah-mark` rules from tokens.css — the lockup's whole geometry — with comments stripped and
 * whitespace collapsed. A missing section throws rather than yielding an empty string, so a rename
 * in tokens.css fails generation and the test instead of shipping an unstyled lockup.
 */
export function lockupCss(css: string = tokensCss()): string {
	const at = css.indexOf(LOCKUP_SECTION);
	if (at < 0) throw new Error(`tokens.css has no "${LOCKUP_SECTION}" section`);
	const start = css.lastIndexOf(BANNER, at);
	const next = css.indexOf(BANNER, at);
	const section = css.slice(start, next < 0 ? undefined : next);
	const minified = section
		.replace(/\/\*[\s\S]*?\*\//g, "")
		.replace(/\s+/g, " ")
		.replace(/\s*([{};:,>])\s*/g, "$1")
		.trim();
	if (!minified.includes(".ah-mark__alethia{")) throw new Error("the lockup section of tokens.css holds no .ah-mark__alethia rule");
	return minified;
}

/** The full text of src/brand.generated.ts. */
export function generatedModule(): string {
	return [
		"// SPDX-FileCopyrightText: 2026 Alethia Labs <legal@alethialabs.io>",
		"// SPDX-License-Identifier: AGPL-3.0-only",
		"",
		"// GENERATED by scripts/gen-brand.ts from packages/brand — do not edit by hand.",
		"// Regenerate with `pnpm -F @repo/status gen:brand`; tests/brand.test.ts fails when this file drifts",
		"// from what packages/brand renders. The Worker serves its own favicon because this page is read",
		"// during an incident, and an icon that 404s because a second origin is down is a small lie.",
		"",
		"/** `AlethiaLockup tag=\"labs\"` (packages/brand/src/lockup.tsx), server-rendered. */",
		`export const LOCKUP_HTML = ${JSON.stringify(lockupHtml())};`,
		"",
		"/** The lockup's `.ah-mark` rules from packages/brand/src/tokens.css, minified. */",
		`export const LOCKUP_CSS = ${JSON.stringify(lockupCss())};`,
		"",
		"/** The favicon (packages/brand/src/icon-svg.ts, the vector twin of the sites' icon.tsx). Served at /favicon.svg. */",
		`export const FAVICON_SVG = ${JSON.stringify(faviconSvg())};`,
		"",
	].join("\n");
}
