// Generate the docs' copy of the abuse ceilings table (beta seam REL-S3, #6775).
//
// `lib/abuse/limits.ts` is the one source. This writes `apps/docs/generated/abuse-limits.json`, which
// the docs limits page (`apps/docs/content/docs/reference/limits.mdx`) renders, so the page cannot
// state a number the console does not enforce. GENERATED rather than hand-copied for the usual
// reason: a hand copy detects drift at best, a generated one makes it impossible — and
// `tests/lib/abuse/limits.test.ts` fails when the committed JSON differs from what this would write.
//
// The JSON carries DEFAULTS only. The environment of whoever runs this never leaks into it: an
// operator override is a deployment fact, and the page documents the variable that sets it.
//
// The table is loaded with Node's built-in TypeScript type stripping (unflagged from Node 22.18),
// which is why limits.ts has no imports. On an older Node the import fails and this says so.
//
// Run (repo root): `node apps/console/scripts/gen-abuse-limits.mjs`            — write
//                  `node apps/console/scripts/gen-abuse-limits.mjs --check`    — exit 1 on drift

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const LIMITS_TS = resolve(HERE, "../lib/abuse/limits.ts");
/** Where the docs read the table. Exported so the drift test reads the same path. */
export const OUT = resolve(HERE, "../../docs/generated/abuse-limits.json");

/** The JSON document's schema version; bump when a field is renamed or removed. */
export const SCHEMA_VERSION = 1;

/**
 * Renders the ceilings table as the docs JSON document: one entry per key in `keys` order, with
 * the fields the page needs and the default value only. Pure, so the drift test can call it on the
 * imported table. Throws when a key has no row or a row's key disagrees with its position, so a
 * half-edited table cannot produce a plausible page.
 * @param {Readonly<Record<string, object>>} table
 * @param {readonly string[]} keys
 * @returns {string}
 */
export function renderAbuseLimits(table, keys) {
	const tableKeys = Object.keys(table);
	if (tableKeys.length !== keys.length || !tableKeys.every((k) => keys.includes(k))) {
		throw new Error(
			`ABUSE_LIMIT_KEYS (${keys.join(", ")}) and ABUSE_LIMITS (${tableKeys.join(", ")}) list different ceilings`,
		);
	}
	const limits = keys.map((key) => {
		const row = table[key];
		if (row.key !== key) throw new Error(`ABUSE_LIMITS.${key} carries key "${String(row.key)}"`);
		if (!Number.isInteger(row.defaultValue) || Number(row.defaultValue) < 1) {
			throw new Error(`ABUSE_LIMITS.${key}.defaultValue must be a positive integer, got ${String(row.defaultValue)}`);
		}
		return {
			key,
			surface: row.surface,
			default: row.defaultValue,
			unit: row.unit,
			window: row.window,
			scope: row.scope,
			appliesTo: row.appliesTo,
			env: row.env,
			description: row.description,
			whenReached: row.whenReached,
		};
	});
	const doc = {
		$comment: "GENERATED by apps/console/scripts/gen-abuse-limits.mjs from apps/console/lib/abuse/limits.ts. Do not edit.",
		schemaVersion: SCHEMA_VERSION,
		limits,
	};
	return `${JSON.stringify(doc, null, "\t")}\n`;
}

/** Loads the table, renders it, and writes (or with `--check`, compares) the docs JSON. */
async function main() {
	let mod;
	try {
		mod = await import(pathToFileURL(LIMITS_TS).href);
	} catch (err) {
		throw new Error(
			`could not load ${LIMITS_TS} — this needs Node's TypeScript type stripping (Node >= 22.18). ` +
				`Underlying error: ${err instanceof Error ? err.message : String(err)}`,
		);
	}
	const rendered = renderAbuseLimits(mod.ABUSE_LIMITS, mod.ABUSE_LIMIT_KEYS);
	if (process.argv.includes("--check")) {
		let current = "";
		try {
			current = readFileSync(OUT, "utf8");
		} catch {
			// Missing file is drift, reported below.
		}
		if (current !== rendered) {
			console.error(`${OUT} is stale. Run: node apps/console/scripts/gen-abuse-limits.mjs`);
			process.exit(1);
		}
		console.log(`${OUT} is current.`);
		return;
	}
	mkdirSync(dirname(OUT), { recursive: true });
	writeFileSync(OUT, rendered);
	console.log(`wrote ${OUT}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await main();
}
