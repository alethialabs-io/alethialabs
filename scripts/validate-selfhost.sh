# Tier-0 self-host validation — proves `deploy/install.sh` (the `curl … | sh` installer)
# still stands up cleanly, keeps its idempotency + Caddy auto-TLS wiring, and can't ship an
# instance with unset secrets. Two modes:
#
#   scripts/validate-selfhost.sh            # STATIC — free, hermetic, every-PR proof
#   scripts/validate-selfhost.sh --live     # + LIVE round-trip (needs Docker; brings the stack up)
#
# STATIC checks (no network, no daemon):
#   1. The installer, the secret helpers, the rotation script and the dev generator pass
#      the shell linter (shellcheck -x).
#   2. deploy/selfhost/secrets.manifest — the one list of instance secrets — is honoured:
#        - every `required` entry is generated by the installer (installer column `yes`, and
#          install.sh fills them through deploy/selfhost/secrets.sh);
#        - .env.example carries an EMPTY placeholder for every entry (a `required` one as an
#          uncommented `NAME=` line);
#        - no compose file gives any entry a default (`${NAME:-…}` / `${NAME-…}`);
#        - the console's placeholder digests equal deploy/selfhost/secrets.sh's.
#   3. Every generator runs: a scratch .env is generated from .env.example in a temp dir, and each
#      `required` value is present, not a template placeholder, and of its generator's shape.
#      Values are checked, never printed.
#   4. The prod and self-host compose overlays render with that scratch .env, and the base file
#      refuses to render, naming the variable, when a required secret is empty.
#   5. Caddy auto-TLS is wired: deploy/prod/Caddyfile reads ALETHIA_DOMAIN + ALETHIA_ACME_EMAIL,
#      and the rendered caddy service carries both.
#
# LIVE adds the compose→hero-flow round-trip: bring the stack up, get /api/health 200 through
# Caddy, prove a second `up -d` is a no-op (idempotent), tear down. The real-domain + real-cert
# leg stays a maintainer step (needs DNS + a public box) — see deploy/prod/README.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

INSTALL_SH="deploy/install.sh"
ENV_EXAMPLE=".env.example"
PROD_CADDYFILE="deploy/prod/Caddyfile"
COMPOSE_FILES=(-f docker-compose.yml -f deploy/prod/docker-compose.prod.yml)
SELFHOST_COMPOSE_FILES=(-f docker-compose.yml -f deploy/selfhost/docker-compose.selfhost.yml)
MANIFEST="deploy/selfhost/secrets.manifest"
CONSOLE_SECRETS_TS="apps/console/lib/crypto/secrets.ts"
SHELL_SCRIPTS=("${INSTALL_SH}" deploy/selfhost/secrets.sh deploy/selfhost/rotate-secret.sh scripts/dev-env.sh)

# shellcheck source=SCRIPTDIR/../deploy/selfhost/secrets.sh
. deploy/selfhost/secrets.sh

SCRATCH="$(mktemp -d)"
SCRATCH_ENV="${SCRATCH}/.env"

green() { printf '\033[32m✓\033[0m %s\n' "$1"; }
info()  { printf '\033[1m▸ %s\033[0m\n' "$1"; }
fail()  { printf '\033[31m✗ %s\033[0m\n' "$1" >&2; FAILURES=$((FAILURES + 1)); }

FAILURES=0

# 1. The shell entry points are shellcheck-clean (-x follows the sourced secrets.sh).
check_shellcheck() {
	info "shellcheck ${SHELL_SCRIPTS[*]}"
	if ! command -v shellcheck >/dev/null 2>&1; then
		fail "shellcheck not installed — cannot lint ${SHELL_SCRIPTS[*]} (brew install shellcheck)"
		return
	fi
	local f
	for f in "${SHELL_SCRIPTS[@]}"; do
		if shellcheck -x "${f}"; then
			green "${f} passes shellcheck"
		else
			fail "${f} has shellcheck findings"
		fi
	done
}

# 2. The manifest is honoured by the installer, the template and the compose files.
check_manifest() {
	info "secrets manifest (${MANIFEST})"
	local name presence installer line value f
	if [ -z "$(manifest_secrets all)" ]; then
		fail "found no secret records in ${MANIFEST} — has it changed shape?"
		return
	fi
	if grep -q 'fill_required_secrets' "${INSTALL_SH}" && grep -q 'deploy/selfhost/secrets.sh' "${INSTALL_SH}"; then
		green "${INSTALL_SH} generates the manifest's required entries through secrets.sh"
	else
		fail "${INSTALL_SH} no longer fills the manifest's required entries (fill_required_secrets)"
	fi
	for name in $(manifest_secrets all); do
		presence="$(manifest_field "${name}" 4)"
		installer="$(manifest_field "${name}" 5)"
		if [ "${presence}" = "required" ] && [ "${installer}" != "yes" ]; then
			fail "${name} is required but its installer column is '${installer}', not 'yes'"
		fi
		[ -n "$(generator_hint "${name}")" ] || fail "${name} names generator '$(manifest_field "${name}" 3)', which ${MANIFEST} does not define"
		# .env.example: an empty placeholder. Only the length of a value is ever looked at.
		line="$(grep -E "^#?[[:space:]]*${name}=" "${ENV_EXAMPLE}" | tail -n 1 || true)"
		value="${line#*=}"
		if [ "${presence}" = "required" ] && ! grep -qE "^${name}=" "${ENV_EXAMPLE}"; then
			fail "${name} is required but ${ENV_EXAMPLE} has no uncommented '${name}=' line"
		elif [ -n "${line}" ] && [ -n "${value}" ]; then
			fail "${name} has a value in ${ENV_EXAMPLE} — the template carries an empty placeholder only"
		fi
		for f in docker-compose.yml docker-compose.dev.yml deploy/prod/*.yml deploy/selfhost/*.yml; do
			if grep -qE "\\\$\{${name}:?-" "${f}"; then
				fail "${f} gives ${name} a default — every instance secret is required with no default"
			fi
		done
	done
	local ts_digests sh_digests
	ts_digests="$(grep -oE '"[0-9a-f]{64}"' "${CONSOLE_SECRETS_TS}" | tr -d '"' | sort | tr '\n' ' ')"
	sh_digests="$(printf '%s' "${PLACEHOLDER_DIGESTS}" | tr ' ' '\n' | sort | tr '\n' ' ')"
	if [ "${ts_digests}" = "${sh_digests}" ]; then
		green "placeholder digests agree (${CONSOLE_SECRETS_TS} ↔ deploy/selfhost/secrets.sh)"
	else
		fail "placeholder digests differ between ${CONSOLE_SECRETS_TS} and deploy/selfhost/secrets.sh"
	fi
	[ "${FAILURES}" -gt 0 ] || green "every manifest entry is generated, has an empty placeholder, and has no compose default"
}

# shape_ok GENERATOR VALUE — whether VALUE has the shape GENERATOR makes.
shape_ok() {
	local bytes
	case "$1" in
		hex16) [[ "$2" =~ ^[0-9a-f]{32}$ ]] ;;
		hex24) [[ "$2" =~ ^[0-9a-f]{48}$ ]] ;;
		hex32) [[ "$2" =~ ^[0-9a-f]{64}$ ]] ;;
		base64-32 | ed25519-raw)
			bytes="$(printf '%s' "$2" | openssl base64 -d -A 2>/dev/null | wc -c | tr -d ' ')"
			if [ "$1" = "base64-32" ]; then [ "${bytes}" = 32 ]; else [ "${bytes}" = 64 ]; fi ;;
		rsa-2048-pem | ec-p256-pem)
			printf '%s' "$2" | openssl base64 -d -A 2>/dev/null | openssl pkey -noout 2>/dev/null ;;
		*) return 1 ;;
	esac
}

# 3. Every generator runs and makes a value of its shape, into a scratch .env (never printed).
check_generators() {
	info "generate every required secret into a scratch .env"
	local filled name value gen
	(umask 077 && cp "${ENV_EXAMPLE}" "${SCRATCH_ENV}")
	if ! filled="$(fill_required_secrets "${SCRATCH_ENV}")"; then
		fail "a generator failed while filling ${SCRATCH_ENV}"
		return
	fi
	for name in $(manifest_secrets required); do
		value="$(env_get "${name}" "${SCRATCH_ENV}")"
		gen="$(manifest_field "${name}" 3)"
		if [ -z "${value}" ]; then
			fail "${name}: the generator left it empty"
		elif is_placeholder "${value}"; then
			fail "${name}: the generated value is a template placeholder"
		elif ! shape_ok "${gen}" "${value}"; then
			fail "${name}: the generated value is not ${gen}-shaped"
		else
			green "${name} generated (${gen})"
		fi
	done
	[ -n "$(fill_required_secrets "${SCRATCH_ENV}")" ] && fail "a second fill rewrote values — it must only fill missing ones"
	: "${filled}"
}

# 4. The overlays render with the generated .env; an empty required secret stops the render.
#    Several services carry `env_file: .env`, resolved in the repository root. When there is none
#    (CI, a fresh clone), the scratch .env is copied there for the check and removed afterwards.
RENDERED_COMPOSE=""
TEMP_ENV_CREATED=0
cleanup() {
	[ "${TEMP_ENV_CREATED}" -eq 1 ] && rm -f "${ROOT}/.env"
	rm -rf "${SCRATCH}"
}
trap cleanup EXIT

check_compose_renders() {
	info "docker compose config (base + prod overlay, base + self-host overlay)"
	if ! command -v docker >/dev/null 2>&1; then
		fail "docker not installed — cannot render the compose overlays"
		return
	fi
	if [ ! -s "${SCRATCH_ENV}" ]; then
		fail "no scratch .env (the generator check failed) — cannot render the overlays"
		return
	fi
	if [ ! -f "${ROOT}/.env" ]; then
		(umask 077 && cp "${SCRATCH_ENV}" "${ROOT}/.env")
		TEMP_ENV_CREATED=1
	fi
	local err
	if RENDERED_COMPOSE="$(docker compose --env-file "${SCRATCH_ENV}" "${COMPOSE_FILES[@]}" config 2>/dev/null)"; then
		green "prod compose overlay renders"
	else
		err="$(docker compose --env-file "${SCRATCH_ENV}" "${COMPOSE_FILES[@]}" config 2>&1 >/dev/null || true)"
		fail "docker compose config failed for the prod overlay: ${err}"
		RENDERED_COMPOSE=""
	fi
	if ALETHIA_VERSION=v0.0.0-validate docker compose --env-file "${SCRATCH_ENV}" "${SELFHOST_COMPOSE_FILES[@]}" config >/dev/null 2>&1; then
		green "self-host compose overlay renders"
	else
		err="$(ALETHIA_VERSION=v0.0.0-validate docker compose --env-file "${SCRATCH_ENV}" "${SELFHOST_COMPOSE_FILES[@]}" config 2>&1 >/dev/null || true)"
		fail "docker compose config failed for the self-host overlay: ${err}"
	fi
	# Negative: with one required secret emptied, the base file must refuse and name it.
	local blank="${SCRATCH}/blank.env"
	(umask 077 && cp "${SCRATCH_ENV}" "${blank}")
	env_set ALETHIA_CRED_ENCRYPTION_KEY "" "${blank}"
	err="$(docker compose --env-file "${blank}" -f docker-compose.yml config 2>&1 >/dev/null || true)"
	if printf '%s' "${err}" | grep -q 'ALETHIA_CRED_ENCRYPTION_KEY'; then
		green "docker-compose.yml refuses an empty ALETHIA_CRED_ENCRYPTION_KEY, naming it"
	else
		fail "docker-compose.yml rendered with ALETHIA_CRED_ENCRYPTION_KEY empty — a required secret has a default"
	fi
}

# 4. Caddy auto-TLS wiring: the Caddyfile reads the env vars, and the rendered caddy service carries them.
check_caddy_tls_wiring() {
	info "Caddy auto-TLS wiring"
	local var
	for var in ALETHIA_DOMAIN ALETHIA_ACME_EMAIL; do
		if grep -qE "\{\\\$${var}" "${PROD_CADDYFILE}"; then
			green "${PROD_CADDYFILE} reads \${${var}}"
		else
			fail "${PROD_CADDYFILE} does not reference \${${var}} — auto-TLS would not pick up the domain/email"
		fi
	done
	if [ -z "${RENDERED_COMPOSE}" ]; then
		fail "cannot assert the caddy service env (compose did not render)"
		return
	fi
	for var in ALETHIA_DOMAIN ALETHIA_ACME_EMAIL; do
		if printf '%s\n' "${RENDERED_COMPOSE}" | grep -qE "^\s+${var}:"; then
			green "rendered caddy service passes ${var}"
		else
			fail "rendered compose does not pass ${var} to the caddy service"
		fi
	done
}

# --- LIVE round-trip (opt-in) ----------------------------------------------------------------
HEALTH_URL="${HEALTH_URL:-http://localhost/api/health}"
LIVE_TIMEOUT="${LIVE_TIMEOUT:-180}"

live_up() { docker compose "${COMPOSE_FILES[@]}" up -d --remove-orphans; }

check_live_roundtrip() {
	info "LIVE round-trip (compose → /api/health → idempotent re-run)"
	command -v docker >/dev/null 2>&1 || { fail "docker required for --live"; return; }

	info "pulling + starting the stack…"
	docker compose "${COMPOSE_FILES[@]}" pull
	live_up

	info "waiting for ${HEALTH_URL} (up to ${LIVE_TIMEOUT}s)…"
	local waited=0 ok=0
	while [ "${waited}" -lt "${LIVE_TIMEOUT}" ]; do
		if curl -fsS -o /dev/null "${HEALTH_URL}" 2>/dev/null; then ok=1; break; fi
		sleep 5; waited=$((waited + 5))
	done
	if [ "${ok}" -eq 1 ]; then green "hero-flow health 200 through Caddy after ${waited}s"; else fail "health never came up within ${LIVE_TIMEOUT}s"; fi

	# A healthy page is not enough for remote MCP: the server's 401 challenge must point to
	# metadata that survives both well-known hops as JSON. This is the deployed regression arm
	# for #3504/#3516, kept beside the repository's existing curl-based deployment probe.
	local mcp_base="${MCP_BASE_URL:-${HEALTH_URL%/api/health}}"
	if scripts/check-mcp-discovery.sh "${mcp_base}"; then
		green "MCP OAuth discovery chain is reachable"
	else
		fail "MCP OAuth discovery chain is broken"
	fi

	# Idempotent re-run: a second `up -d` must not recreate anything.
	info "asserting a second up -d is idempotent…"
	local second
	second="$(live_up 2>&1 || true)"
	if printf '%s\n' "${second}" | grep -qiE 'Recreat|Recreating|Created'; then
		fail "second up -d recreated containers — not idempotent:\n${second}"
	else
		green "second up -d made no changes (idempotent)"
	fi

	# Real-domain cert assertion is only meaningful with a public DOMAIN + DNS — maintainer-gated.
	if [ -n "${DOMAIN:-}" ]; then
		info "DOMAIN set — a real cert should be in the caddy-data volume (maintainer verifies on the box)"
	fi

	info "tearing the stack down…"
	docker compose "${COMPOSE_FILES[@]}" down >/dev/null 2>&1 || true
}

main() {
	local live=0
	[ "${1:-}" = "--live" ] && live=1

	check_shellcheck
	check_manifest
	check_generators
	check_compose_renders
	check_caddy_tls_wiring
	[ "${live}" -eq 1 ] && check_live_roundtrip

	echo
	if [ "${FAILURES}" -eq 0 ]; then
		green "self-host Tier-0 validation passed"
	else
		fail "${FAILURES} check(s) failed"
		exit 1
	fi
}

main "$@"
