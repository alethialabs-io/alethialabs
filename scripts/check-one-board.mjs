// One board — a hand-maintained status board under `docs/testing/` must be declared.
//
// WHY THIS EXISTS. `PROGRAMME.md` was built because fifteen hand-maintained boards had accumulated
// under `docs/testing/` and had begun contradicting each other IN THE TREE while passing CI. The
// rollup's own header names the case:
//
//   · provisioning-e2e-parity.md cited #1714/#1716/#1722/#2058 as OPEN blockers. All four are CLOSED.
//   · runner-xcloud-parity.md says hetzner is green (nightly) for cluster provision while
//     provisioning-e2e-parity.md says blocked — two files, one directory, contradicting each
//     other, both passing CI.
//
// PROGRAMME.md §3 says its intent-half grep is "the only structural reason a 16th hand-maintained
// board cannot re-emerge inside this very file". Inside THAT FILE. Nothing stopped a new one
// appearing beside it, and nothing in CI read any of the twelve.
//
// So: a file under `docs/testing/` that asserts STATUS must either be GENERATED — carrying a
// generator marker and a diff gate, as offer-parity.md, config-carriage.md and template-parity.md
// already do — or be named in `docs/testing/one-board-allowlist.yaml` with a reason and, where one
// exists, the condition that would retire it. The list only shrinks.
//
// WHAT COUNTS AS STATUS is not defined here. It is imported from programme-rollup.mjs, which
// already answers exactly that question for PROGRAMME.md's intent half. Two definitions of "this
// line asserts status" would be the drift both guards exist to stop.
//
// Usage:  node scripts/check-one-board.mjs [--self-test]
// Wired into CI's `Authz / open-core guards` job.

import { readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { statusClaimsIn } from "./programme-rollup.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BOARDS_DIR = "docs/testing";
const ALLOWLIST = "docs/testing/one-board-allowlist.yaml";

// A census floor. A glob that stops matching — a rename, a moved directory — would otherwise
// report "0 boards, 0 problems" and pass. "Nothing found" and "nothing wrong" must not share an
// exit code.
const MIN_BOARDS = 10;

/** A file carrying one of these is generated and diff-gated; its content is not hand-maintained. */
const GENERATED_MARKER = /GENERATED by|do not edit by hand|DO NOT EDIT/i;

/**
 * Parse the allowlist without pretending to parse YAML.
 *
 * The shape is deliberately the same as `apps/console/shared-surface-allowlist.yaml`: a list of
 * entries, each with a `path` and a `reason`. `retires_when` is optional prose naming what would
 * let the entry go — a board tracking a dimension the rollup does not model is legitimate today
 * and should say what would change that.
 *
 * @param {string} src
 * @returns {{path: string, reason: string, retiresWhen: string}[]}
 */
function parseAllowlist(src) {
	const out = [];
	let cur = null;
	for (const raw of src.split("\n")) {
		const line = raw.replace(/\r$/, "");
		if (/^\s*#/.test(line) || line.trim() === "") continue;
		const path = /^\s*-\s*path:\s*(.+?)\s*$/.exec(line);
		if (path) {
			if (cur) out.push(cur);
			cur = { path: path[1].replace(/^["']|["']$/g, ""), reason: "", retiresWhen: "" };
			continue;
		}
		if (!cur) continue;
		const reason = /^\s+reason:\s*(.+?)\s*$/.exec(line);
		if (reason) cur.reason = reason[1].replace(/^["']|["']$/g, "");
		const retires = /^\s+retires_when:\s*(.+?)\s*$/.exec(line);
		if (retires) cur.retiresWhen = retires[1].replace(/^["']|["']$/g, "");
	}
	if (cur) out.push(cur);
	return out;
}

/**
 * Apply the rule to already-read inputs. Separated from I/O so `--self-test` can drive it.
 *
 * @param {{name: string, content: string}[]} boards
 * @param {{path: string, reason: string}[]} allowed
 * @returns {string[]}
 */
function check(boards, allowed) {
	const problems = [];
	const allowedByPath = new Map(allowed.map((a) => [a.path, a]));
	const claimed = new Set();

	for (const board of boards) {
		const rel = `${BOARDS_DIR}/${board.name}`;
		if (GENERATED_MARKER.test(board.content)) {
			if (allowedByPath.has(rel)) {
				// Consume the entry as well as reporting it. Without this the stale-entry loop
				// below reports the SAME entry a second time as "no longer asserts status", which
				// is a different and false statement about the file — the kind a reader trusts
				// because it came from a guard.
				claimed.add(rel);
				problems.push(
					`${ALLOWLIST}: \`${rel}\` is GENERATED and does not need an allowlist entry — remove it. ` +
						`An entry over a generated file makes the list look longer than the debt actually is.`,
				);
			}
			continue;
		}
		const claims = statusClaimsIn(board.content);
		if (claims.length === 0) continue;

		const entry = allowedByPath.get(rel);
		if (!entry) {
			const first = claims[0];
			problems.push(
				`${rel}:${first.line}: a hand-maintained status claim (${claims.length} in this file), and the file ` +
					`is neither generated nor allowlisted.\n      ${first.text.trim().slice(0, 110)}\n` +
					`      Either derive it (a generator + a \`git diff --exit-code\` gate, as offer-parity.md does), ` +
					`or add an entry to ${ALLOWLIST} saying why this one is hand-maintained.`,
			);
			continue;
		}
		claimed.add(rel);
		if (entry.reason.length < 25) {
			problems.push(`${ALLOWLIST}: \`${rel}\` has no real reason — "${entry.reason}" is too short to be one.`);
		}
	}

	// A stale entry is its own failure: it makes the list look bigger than the debt, and the list
	// is supposed to only shrink.
	for (const entry of allowed) {
		if (!claimed.has(entry.path)) {
			const exists = boards.some((b) => `${BOARDS_DIR}/${b.name}` === entry.path);
			problems.push(
				exists
					? `${ALLOWLIST}: \`${entry.path}\` no longer asserts status — delete its entry. The list only shrinks.`
					: `${ALLOWLIST}: \`${entry.path}\` does not exist — delete its entry.`,
			);
		}
	}
	return problems;
}

/** Prove the guard can fail, in both directions and for each shape. */
function selfTest() {
	const cases = [
		["a board with no status claim needs no entry", [{ name: "runbook.md", content: "# Runbook\n\nRun `pnpm x`.\n" }], [], 0],
		[
			"a verdict glyph without an entry FAILS",
			[{ name: "b.md", content: "| aws | ✅ |\n" }],
			[],
			1,
		],
		[
			"a derived count without an entry FAILS",
			[{ name: "b.md", content: "We have 3 of 5 cells proven today.\n" }],
			[],
			1,
		],
		[
			"an is-green claim without an entry FAILS",
			[{ name: "b.md", content: "hetzner is now green for provisioning.\n" }],
			[],
			1,
		],
		[
			"a GENERATED board is exempt however many glyphs it carries",
			[{ name: "g.md", content: "<!-- GENERATED by x --matrix — do not edit by hand. -->\n| aws | ✅ |\n" }],
			[],
			0,
		],
		[
			"an allowlisted board with a real reason PASSES",
			[{ name: "b.md", content: "| aws | ✅ |\n" }],
			[{ path: "docs/testing/b.md", reason: "tracks a dimension the rollup does not model yet", retiresWhen: "" }],
			0,
		],
		[
			"an allowlist entry whose reason is a placeholder FAILS",
			[{ name: "b.md", content: "| aws | ✅ |\n" }],
			[{ path: "docs/testing/b.md", reason: "n/a", retiresWhen: "" }],
			1,
		],
		[
			"an entry for a board that no longer claims status FAILS (the list only shrinks)",
			[{ name: "b.md", content: "# Just prose now.\n" }],
			[{ path: "docs/testing/b.md", reason: "tracks a dimension the rollup does not model yet", retiresWhen: "" }],
			1,
		],
		[
			"an entry for a file that does not exist FAILS",
			[{ name: "b.md", content: "# prose\n" }],
			[{ path: "docs/testing/gone.md", reason: "tracks a dimension the rollup does not model yet", retiresWhen: "" }],
			1,
		],
		[
			"an entry over a GENERATED board FAILS",
			[{ name: "g.md", content: "<!-- GENERATED by x -->\n| aws | ✅ |\n" }],
			[{ path: "docs/testing/g.md", reason: "tracks a dimension the rollup does not model yet", retiresWhen: "" }],
			1,
		],
		[
			"a citation is not a claim — the rule can be documented without tripping it",
			[{ name: "b.md", content: 'Never write "is green" in a board.\n' }],
			[],
			0,
		],
	];

	let failed = 0;
	for (const [name, boards, allowed, want] of cases) {
		const got = check(boards, allowed);
		if (got.length === want) {
			console.log(`  ✓ ${name}`);
		} else {
			failed++;
			console.error(`  ✗ ${name}: expected ${want} problem(s), got ${got.length}`);
			got.forEach((p) => console.error(`      ${p.split("\n")[0]}`));
		}
	}

	// The allowlist parser is the other thing that can silently go blind.
	const parsed = parseAllowlist(
		'# a comment\n- path: docs/testing/a.md\n  reason: because it tracks a thing the rollup cannot see\n  retires_when: the rollup models it\n- path: docs/testing/b.md\n  reason: another real reason that is long enough\n',
	);
	if (parsed.length !== 2 || parsed[0].retiresWhen !== "the rollup models it" || !parsed[1].reason.startsWith("another")) {
		failed++;
		console.error(`  ✗ allowlist parser: got ${JSON.stringify(parsed)}`);
	} else {
		console.log("  ✓ the allowlist parser reads path, reason and retires_when");
	}

	if (failed > 0) {
		console.error(`\nFAIL: ${failed} self-test case(s) failed — the guard itself is broken`);
		process.exit(1);
	}
	console.log("\nOK: self-test passed");
}

function main() {
	if (process.argv.includes("--self-test")) {
		selfTest();
		return;
	}

	let names;
	try {
		names = readdirSync(join(ROOT, BOARDS_DIR)).filter((f) => f.endsWith(".md"));
	} catch (err) {
		console.error(`FAIL: cannot read ${BOARDS_DIR} — ${err.message}`);
		process.exit(1);
	}
	if (names.length < MIN_BOARDS) {
		console.error(
			`FAIL: found ${names.length} board(s) under ${BOARDS_DIR}, expected at least ${MIN_BOARDS}. ` +
				`Either the directory moved or the glob stopped matching — nothing has been checked. ` +
				`If boards were genuinely removed, lower MIN_BOARDS in the same commit and say why.`,
		);
		process.exit(1);
	}

	let allowSrc;
	try {
		allowSrc = readFileSync(join(ROOT, ALLOWLIST), "utf8");
	} catch {
		// An absent allowlist must not read as "nothing is allowlisted, so everything is fine".
		console.error(
			`FAIL: ${ALLOWLIST} is missing. An absent allowlist is not an empty one — without it this ` +
				`guard cannot tell a declared hand-maintained board from an undeclared one, and has ` +
				`checked nothing.`,
		);
		process.exit(1);
	}

	const boards = names.map((name) => ({ name, content: readFileSync(join(ROOT, BOARDS_DIR, name), "utf8") }));
	const allowed = parseAllowlist(allowSrc);
	const generated = boards.filter((b) => GENERATED_MARKER.test(b.content)).length;
	const problems = check(boards, allowed);

	console.log(
		`one board: ${boards.length} file(s) under ${BOARDS_DIR} — ${generated} generated, ` +
			`${allowed.length} hand-maintained and declared`,
	);
	if (problems.length > 0) {
		console.error(`\nFAIL: ${problems.length} problem(s)\n`);
		problems.forEach((p) => console.error(`  ${p}`));
		console.error(
			`\nPROGRAMME.md is the board. A status claim under ${BOARDS_DIR} either derives from the ` +
				`ledger — with a generator and a diff gate — or is declared with the reason it is still ` +
				`written by hand.`,
		);
		process.exit(1);
	}
	console.log("OK: every status claim under docs/testing is generated or declared");
}

main();
